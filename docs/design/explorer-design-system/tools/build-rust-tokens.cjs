// Generate Rust palette from the same semantic tokens as the HTML reference.
const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'..');
const data=JSON.parse(fs.readFileSync(path.join(root,'tokens.json'),'utf8'));
function rgba(s){
 if(s==='transparent')return '0x00000000';
 if(s==='currentColor')return '0x0f172aff';
 if(s.startsWith('#'))return '0x'+s.slice(1)+(s.length===7?'ff':'');
 const n=s.match(/[\d.]+/g).map(Number);return '0x'+[...n.slice(0,3),Math.round((n[3]??1)*255)].map(v=>v.toString(16).padStart(2,'0')).join('');
}
const arms=Object.entries(data.color).map(([k,v])=>'        "'+k+'" => if dark { rgba('+rgba(v.dark)+') } else { rgba('+rgba(v.light)+') },').join('\n');
const output='// Generated by build-rust-tokens.cjs; edit tokens.json.\nuse gpui::{Rgba, rgba};\n#[rustfmt::skip]\npub fn color(name: &str, dark: bool) -> Rgba {\n    match name {\n'+arms+'\n        _ => panic!("unknown design token: {name}"),\n    }\n}\n';
const dest=path.resolve(root,'../../../apps/explorer/src/theme_tokens.rs');
if(process.argv.includes('--check')){if(fs.readFileSync(dest,'utf8').replace(/\r\n/g,'\n')!==output){console.error('Rust tokens drift');process.exit(1)}}else fs.writeFileSync(dest,output);
